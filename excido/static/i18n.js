const STORE_KEY = "excido.lang";
export const LANGS = ["en", "it"];

// English by default; the EN/IT switch in the top bar remembers the user's choice.
function detect() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage unavailable */ }
  return "en";
}

let lang = detect();

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = LANGS.includes(next) ? next : "en";
  try { localStorage.setItem(STORE_KEY, lang); } catch {}
  document.documentElement.lang = lang;
  applyI18n();
}

/** Translate `key`, replacing {placeholders}. Falls back to English, then to `fallback`, then to the key. */
export function t(key, vars = {}, fallback) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? fallback ?? key;
  vars = { mod: MOD, ...vars };
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Pick the ".one" / ".other" variant of `key` for count `n`. */
export function tn(key, n, vars = {}) {
  return t(`${key}.${n === 1 ? "one" : "other"}`, { n, ...vars });
}

/** True if a translation exists in the current language (used for model texts). */
export function has(key) {
  return key in STRINGS[lang];
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
}

document.documentElement.lang = lang;
